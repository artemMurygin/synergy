import type { BaseChatModel } from '@langchain/core/language_models/chat_models';
import type { StructuredTool } from '@langchain/core/tools';
import type { SubAgent } from 'deepagents';
import type { Searcher } from '../sheets-qa.config';

const SEARCH_HINT =
    'основа слова без окончания («дизайн» найдёт «дизайнер»), однокоренные слова, синонимы и названия профессий направления, код направления, короткие запросы из одного-двух слов (слова одного запроса должны быть в одной ячейке), другое написание (латиница и кириллица). В ответе у ячейки поле queries: чем больше запросов сработало, тем лучше подходит строка';

function buildEducationPrompt(level: Searcher): string {
    const sheet = level.sheets.join('», «');
    return `Ты ищешь программы направления «${level.level}» в прайсе — листе «${sheet}» книги ценовой политики. Читай только этот лист. Книга — единственный источник правды.

Порядок работы:
1. Вызови read_sheet_guide с названием «${sheet}» и прочитай, как устроены колонки и цены.
2. Найди подходящие строки одним вызовом search_cells (параметр sheet = «${sheet}»), передав в queries сразу все переформулировки запроса: ${SEARCH_HINT}. Затем read_rows по найденным строкам. Если результат пустой, переформулируй и вызови ещё раз.
3. Если на листе несколько блоков со своими шапками (например, колледж, бакалавриат, магистратура), ищи по всем блокам и указывай блок в строке программы. Колонки с той же буквой в разных блоках могут значить разное: сверяйся с описанием листа.
4. Не вызывай find_related и не читай методическую базу: нужен только обзор.

Твой ответ вставляют в итоговый ответ менеджеру без переписывания, поэтому пиши строго в этом формате и ничего лишнего (без вступления, итога и пояснений):
1. **Название программы (код)** — ${level.level} (блок или уровень, если их несколько); форма обучения и база (9 или 11 классов): цена за 1-й год / за следующие, срок; вступительные: есть (какие) или нет. *${sheet}, строка N.*
Если у программы несколько подходящих форм, перечисли их в этой же строке через «;». Цены приводи ровно как в таблице. Нумеруй с 1. Важные пометки из ячеек и шапки листа («набор завершён», «только для жителей Москвы», «нет аккредитации») добавляй в конец строки программы. Если в запросе указано число программ, верни не больше этого числа, самых подходящих. Если подходящих нет, напиши это одной фразой и назови ближайшие варианты с указанием, какое условие они не выполняют. Ничего не выдумывай, не раскрывай логины и пароли.`;
}

function bullets(items: readonly string[]): string {
    return items.map((item) => `- ${item}`).join('\n');
}

function buildCoursePrompt(searcher: Searcher): string {
    const book = searcher.book;
    return `Ты ищешь курсы и программы ДПО в книге «${book}» (направление: ${searcher.level}). Книга — единственный источник правды. Во ВСЕХ вызовах инструментов (read_sheet_guide, list_sheets, search_cells, read_rows, get_row_links) обязательно передавай book = «${book}»: без него инструменты читают другую книгу.

Листы для поиска:
${bullets(searcher.sheets.map((sheet) => `«${sheet.trim()}»`))}
${
    searcher.ignoreSheets === undefined || searcher.ignoreSheets.length === 0
        ? ''
        : `\nНе используй как источник (или только с оговоркой, указанной в скобках):\n${bullets(searcher.ignoreSheets)}\n`
}
Как устроена строка курса в этой книге:
${searcher.rowFormat ?? 'смотри описание листа.'}

Подводные камни книги (они меняют ответ, учитывай их):
${bullets(searcher.pitfalls ?? [])}

Порядок работы:
1. Вызови read_sheet_guide (book = «${book}») без названия листа, затем с названием нужного листа и прочитай, как устроены колонки и цены.
2. Найди подходящие строки ОДНИМ вызовом search_cells (book = «${book}»), передав в queries сразу все переформулировки запроса: ${SEARCH_HINT}. Затем read_rows по найденным строкам. Если результат пустой, переформулируй и вызови ещё раз.
3. Не вызывай find_related и не ходи в другие книги: нужен только обзор по этой книге.

Твой ответ вставляют в итоговый ответ менеджеру без переписывания, поэтому пиши строго в этом формате и ничего лишнего (без вступления, итога и пояснений):
1. **Название курса** — вид (ПП/ПК/ДО/ПО, если он указан в книге); часы; срок; цена (ровно как в таблице, с пояснением, к чему относится каждая цена: тариф, скидка, рассрочка); форма обучения; документ. *Книга «${book}», лист «…», строка N.* Пометки: скрытая строка или лист, устаревшая дата, две цены или расхождение цен, набор закрыт.
Чего нет в книге, пиши «в таблице не указано», а не угадывай. Если у курса несколько вариантов (тарифы, часы, ПП и ПК), перечисли их в этой же строке через «;». Нумеруй с 1. Если в запросе указано число курсов, верни не больше этого числа, самых подходящих. Если подходящих нет, напиши это одной фразой и назови ближайшие варианты с указанием, какое условие они не выполняют. Ничего не выдумывай. Никогда не раскрывай логины, пароли, учётные данные демо-доступов, личные контакты (телефоны, e-mail, Telegram) и приглашения в закрытые чаты: если это нужно для ответа, направь менеджера к ячейке книги.`;
}

/** Prompt of one searcher: the education ones read the default book, the course ones name theirs. */
export function buildSearcherPrompt(searcher: Searcher): string {
    return searcher.branch === 'courses'
        ? buildCoursePrompt(searcher)
        : buildEducationPrompt(searcher);
}

/** One searcher per education level or book; the main agent starts them in parallel. */
export function buildLevelSubagents(
    levels: readonly Searcher[],
    tools: StructuredTool[],
    model: BaseChatModel,
): SubAgent[] {
    return levels.map((level) => ({
        name: level.agent,
        description:
            level.branch === 'courses'
                ? `Ищет курсы и ДПО в книге «${level.book}» (${level.covers}) по условиям клиента и возвращает готовые строки курсов с ценами и источниками. В задаче укажи тему курса, вид (ПП/ПК/ДО), бюджет, срок и сколько курсов нужно.`
                : `Ищет в прайсе («${level.sheets.join('», «')}») программы направления «${level.level}» (${level.covers}) по условиям клиента и возвращает краткий список с ценами и источниками. В задаче укажи направление, форму обучения, базу (9/11 классов), бюджет и сколько программ нужно.`,
        systemPrompt: buildSearcherPrompt(level),
        tools,
        model,
    }));
}
